import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';

test('real room: protected host controls, file transfer, readiness and shared playback', async t => {
  const port = 33000 + Math.floor(Math.random()*10000);
  const child = spawn(process.execPath, ['server.mjs'], {cwd:new URL('..',import.meta.url),env:{...process.env,PORT:String(port)},stdio:['ignore','pipe','pipe']});
  t.after(() => child.kill());
  let logs='';
  await new Promise((resolve,reject) => {
    const timeout=setTimeout(()=>reject(new Error('Server startup timed out')),10000);
    child.once('error',reject);
    child.stdout.on('data',chunk=>{ logs+=chunk; if(logs.includes('Press Ctrl+C')) {clearTimeout(timeout);resolve();} });
    child.once('exit',code=>{clearTimeout(timeout);reject(new Error(`Server exited ${code}`));});
  });
  const host=logs.match(/host=([a-f0-9]+)/)[1];
  const base=`http://127.0.0.1:${port}`;
  const bootstrap=await fetch(base+'/api/bootstrap',{method:'POST',body:JSON.stringify({host})}).then(r=>r.json());
  const key=bootstrap.key;
  const request=async(path,data,token='',extra={})=>{
    const response=await fetch(`${base}/api/${path}?key=${key}`,{method:data===undefined?'GET':'POST',headers:{'x-host-token':token,...extra.headers},...(data===undefined?{}:{body:JSON.stringify(data)}),...extra});
    return {status:response.status,body:await response.json()};
  };
  assert.equal((await fetch(base+'/')).status,200);
  assert.equal((await fetch(base+'/api/state')).status,403);
  assert.equal((await request('clock')).status,200);
  const a=(await request('join',{name:'Phone'})).body;
  const b=(await request('join',{name:'Laptop'})).body;
  assert.equal((await request('device',{id:a.id,secret:b.secret,volume:.2})).status,403);
  assert.equal((await request('device',{id:a.id,secret:a.secret,role:'left'})).status,200);
  assert.equal((await request('transport',{action:'play'})).status,403);
  assert.equal((await request('upload',undefined,'',{method:'POST',body:Buffer.from('test')})).status,403);
  const bytes=Buffer.from('test audio bytes');
  const uploaded=await request('upload',undefined,host,{method:'POST',headers:{'x-host-token':host,'x-file-name':'sample.wav'},body:bytes});
  assert.equal(uploaded.status,200);
  const current=(await request('state')).body;
  assert.equal(current.track.name,'sample.wav');
  assert.ok(current.devices.every(d=>!('secret' in d)));
  const download=await fetch(`${base}/api/audio?key=${key}&track=${current.track.id}`);
  assert.deepEqual(Buffer.from(await download.arrayBuffer()),bytes);
  assert.equal((await request('transport',{action:'duration',duration:30},host)).status,200);
  assert.equal((await request('transport',{action:'play'},host)).status,409);
  for(const d of [a,b]) assert.equal((await request('device',{...d,armed:true,readyTrack:current.track.id})).status,200);
  const before=Date.now();
  assert.equal((await request('transport',{action:'play'},host)).status,200);
  const playing=(await request('state')).body;
  assert.equal(playing.transport.playing,true);
  assert.ok(playing.transport.startsAt>=before+1700);
  assert.equal((await request('transport',{action:'seek',position:12},host)).status,200);
  assert.equal((await request('state')).body.transport.position,12);
  assert.equal((await request('transport',{action:'pause'},host)).status,200);
  assert.equal((await request('state')).body.transport.playing,false);
  assert.equal((await request('device',{id:b.id,volume:.2,delay:25},host)).status,200);
  assert.equal((await request('transport',{action:'seek',position:'bad'},host)).status,400);
  assert.equal((await fetch(base+'/../server.mjs')).status,404);
  const event=await fetch(`${base}/api/events?key=${key}`);
  const reader=event.body.getReader();
  assert.match(new TextDecoder().decode((await reader.read()).value),/^data: /);
  await reader.cancel();
  await request('upload',undefined,host,{method:'POST',headers:{'x-host-token':host},body:Buffer.from('new audio')});
  const replaced=(await request('state')).body;
  assert.equal(replaced.transport.playing,false);
  assert.ok(replaced.devices.every(d=>d.readyTrack===null));
  assert.equal((await request('live-start',{sampleRate:48000})).status,403);
  const liveSession=await request('live-start',{sampleRate:48000,name:'Online music'},host);
  assert.equal(liveSession.status,200);
  const liveId=liveSession.body.id;
  assert.equal((await request('state')).body.track,null);
  assert.equal((await request('live-control',{id:liveId,action:'stop'})).status,403);
  const liveEvents=await fetch(`${base}/api/events?key=${key}`,{signal:AbortSignal.timeout(5000)});
  const liveReader=liveEvents.body.getReader();
  await liveReader.read(); // Initial room state.
  const packet=Buffer.alloc(8+4800*8);packet.writeDoubleLE(0,0);packet.writeFloatLE(.25,8);
  const push=async(body,token=host)=>fetch(`${base}/api/live-chunk?key=${key}&id=${liveId}`,{method:'POST',headers:{'x-host-token':token},body});
  assert.equal((await push(packet,'')).status,403);
  assert.equal((await push(packet)).status,200);
  let emitted='';
  while(!emitted.includes('event: audio')) emitted+=new TextDecoder().decode((await liveReader.read()).value);
  assert.match(emitted,/"sampleRate":48000/);
  assert.match(emitted,/"frames":4800/);
  assert.equal((await request('device',{...a,armed:true,readyTrack:`live:${liveId}`})).status,200);
  assert.equal((await request('state')).body.devices.find(d=>d.id===a.id).readyTrack,`live:${liveId}`);
  assert.equal((await request('live-control',{id:liveId,action:'pause'},host)).status,200);
  assert.equal((await request('state')).body.live.paused,true);
  packet.writeDoubleLE(4800,0);assert.equal((await push(packet)).status,200);
  assert.equal((await request('live-control',{id:liveId,action:'resume'},host)).status,200);
  assert.equal((await request('live-control',{id:liveId,action:'stop'},host)).status,200);
  assert.equal((await request('state')).body.live,null);
  assert.equal((await push(packet)).status,409);
  await liveReader.cancel();
  const eq={enabled:true,bass:3,mid:-1,treble:2};
  assert.equal((await request('eq-all',{eq})).status,403);
  assert.equal((await request('device',{id:a.id,secret:b.secret,eq})).status,403);
  assert.equal((await request('device',{...a,eq})).status,200);
  assert.deepEqual((await request('state')).body.devices.find(d=>d.id===a.id).eq,eq);
  assert.equal((await request('eq-all',{eq},host)).status,200);
  const eqState=(await request('state')).body;
  assert.deepEqual(eqState.roomEq,eq);
  assert.ok(eqState.devices.every(d=>JSON.stringify(d.eq)===JSON.stringify(eq)));
  const newcomer=(await request('join',{name:'New speaker'})).body;
  assert.deepEqual((await request('state')).body.devices.find(d=>d.id===newcomer.id).eq,eq);
  child.kill(); await once(child,'exit');
});
